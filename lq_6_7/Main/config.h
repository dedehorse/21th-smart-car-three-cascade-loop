#define AngleKD     1.2f            /* [s]         微分增益                */
#define AngleIgr    100.0f          /* [°/s]       积分限幅                */

/*╔══════════════════════════════════════════════════════════════════════════════╗
 *║                   5. 角速度环 PID (中环, 位置式, 500Hz)                        ║
 *║      输入: Target_Gyro − 当前角速度 (°/s) → PID输出 (°/s) ×DEG2RAD → rad/s     ║
 *╚══════════════════════════════════════════════════════════════════════════════╝*/
#define GyroKP      30.0f           /* [—] 比例增益, (°/s)/(°/s)=1       */
#define GyroKI      0.0f            /* [1/s] 积分增益 (每2ms)             */
#define GyroKD      5.0f            /* [s] 微分增益                       */
#define GyroIgr     100.0f          /* [°/s] 积分限幅                     */

/*╔══════════════════════════════════════════════════════════════════════════════╗
 *║                   6. 速度环 PID (内环, 增量式, 1000Hz)                         ║
 *║                 输入: 速度误差 (cm/s) → 输出: PWM增量                          ║
 *╚══════════════════════════════════════════════════════════════════════════════╝*/
#define IncKP               3.66f   /* [PWM/(cm/s)] 比例增益              */
#define IncKI               0.005f  /* [PWM/(cm/s)] 积分增益 (每1ms)      */
#define IncKD               0.0f    /* [PWM/(cm/s)] 微分增益              */
#define IncIgr              1500.0f /* [PWM] 积分限幅                     */
#define SPEED_INC_DELTA_MAX 200.0f  /* [PWM/ms] 单周期增量限幅            */
#define SPEED_DEAD_ZONE     5.0f    /* [cm/s]  死区, 误差<此值不响应      */

/*╔══════════════════════════════════════════════════════════════════════════════╗
 *║                        7. 输出限幅                                            ║
 *╚══════════════════════════════════════════════════════════════════════════════╝*/
