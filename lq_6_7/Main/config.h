/*╔══════════════════════════════════════════════════════════════════════════════╗
 *║                        2. 单位转换宏                                          ║
 *╚══════════════════════════════════════════════════════════════════════════════╝*/
/* 内部统一使用 °/s 量纲, 仅在 Gyro_Loop_Update 输出时 DEG2RAD → rad/s → speed */
#define RAD2DEG  57.29578f          /* [—] 180/π, rad→°                  */
#define DEG2RAD  0.017453293f       /* [—] π/180, °→rad                  */

/*╔══════════════════════════════════════════════════════════════════════════════╗
 *║                   3. 方向环 PID (外环A, 位置式, 200Hz)                         ║
 *║                输入: 赛道偏差 (px) → 输出: Target_Gyro (°/s)                    ║
 *╚══════════════════════════════════════════════════════════════════════════════╝*/
#define LocKP          3.5f         /* [(°/s)/px]  比例增益                */
#define LocKI          0.0f         /* [(°/s)/px]  积分增益 (每5ms)        */
#define LocKD          0.35f        /* [(°/s)/(px/5ms)] 微分增益           */
#define LocIgr         100.0f       /* [°/s]       积分限幅                */
#define DIR_FILT_ALPHA 0.3f         /* [—] 低通滤波系数, f_c≈38Hz @200Hz  */

/*╔══════════════════════════════════════════════════════════════════════════════╗
 *║                   4. 角度环 PID (外环B, 位置式, 200Hz)                         ║
 *║                输入: 偏航角误差 (°) → 输出: Target_Gyro (°/s)                  ║
 *║                Angle_Mode=1 时替换方向环成为外环                               ║
 *╚══════════════════════════════════════════════════════════════════════════════╝*/
